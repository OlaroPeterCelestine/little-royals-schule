export function routeById(id: string): NavRoute | undefined {
  return routes.find((item) => item.id === id)
}

export function resolveRoute(pathname: string): NavRoute | undefined {
  const exact = routes.find((item) => item.href === pathname)
  if (exact) return exact
  return routes.find((item) => item.match?.test(pathname))
}

export function breadcrumbTrail(
  pathname: string,
  recordTitle?: string | null,
): { title: string; href: string | null }[] {
  const current = resolveRoute(pathname)
  if (!current) return [{ title: "School OS", href: "/app/dashboard" }]
  const trail: { title: string; href: string | null }[] = []
  const workspace = workspaces.find((item) => item.id === current.workspaceId)
  if (workspace) trail.push({ title: workspace.label, href: null })
  if (current.parentId) {
    const parent = routeById(current.parentId)
    if (parent?.href) trail.push({ title: parent.title, href: parent.href })
  }
  trail.push({ title: recordTitle || current.title, href: current.href })
  return trail
}
